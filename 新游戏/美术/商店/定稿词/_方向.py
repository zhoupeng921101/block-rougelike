"""用 _模板.txt 拼三个方向的定稿词: python -X utf8 _方向.py

提交词不另加开头：_模板.txt 第一行已是「请直接生成一张图片」。
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
tpl = open(os.path.join(HERE, "_模板.txt"), encoding="utf-8").read()
DIRS = {
    "A": "A「武器柜台」（货架就是一排军火）\n"
         "- 四张商品卡的图框是平的深色凹格，图标就放在里面，干干净净；图标画得大而清楚，占图框的七成，是这一屏最抢眼的东西。\n"
         "- 背景只有太空和星星，什么都不加。",
    "B": "B「全息展台」（每件商品浮在一个发光的小底座上）\n"
         "- 四张商品卡的图框下沿是一个扁扁的椭圆形像素小底座，底座往上打一束很淡的青色平滑光柱，图标悬在光柱里、底下一圈淡淡的投影；选中的「七彩基因」光柱更亮一点。\n"
         "- 光柱和辉光都只在图框里面，不出卡片。背景只有太空和星星，什么都不加。",
    "C": "C「上一颗星球的残骸」（商店开在刚打碎的星球旁边）\n"
         "- 四张商品卡的图框是平的深色凹格，图标放在里面。\n"
         "- 背景：画面左下角、左栏下方的空太空里，露出一大块刚被打碎的星球残骸的一角（低饱和的暗红褐、橙褐三四档纯色像素块，裂缝里一点暗橙色的余光），只占左下角那块空地，边缘被画面左边和下边切掉，不伸到任何面板后面；周围飘着五六块小碎石，离残骸越远越小。其余的太空只有星星。",
}
for k, d in DIRS.items():
    txt = tpl.replace("{方向}", d)
    open(os.path.join(HERE, f"商店_v1{k}.txt"), "w", encoding="utf-8").write(txt)
    open(os.path.join(HERE, "..", "提交", "词", f"v1{k}.txt"), "w", encoding="utf-8").write(txt)
print("ok", list(DIRS))
