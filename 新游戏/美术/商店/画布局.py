"""生成商店屏的线框布局 布局_商店.json: python -X utf8 画布局.py

规则 §8.7 草图 + 局外循环 §4：左栏消除类型表、右栏背包照选关屏；中间上方基因槽 2/4 与道具栏 1/2（买了放哪、拿什么卖），
中间货架 4 格（基因 2、科技 1、改造 1），下面优惠券 1 格、补给包 1 格，底部「刷新 $5」「离开商店」。
画的是「结算完进店、选中第 2 格七彩基因」那一态。坐标先按 1920×1080 写，最后整体下移 100 放进 1920×1280。
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PICK = os.path.join(HERE, "..", "选关", "布局_选关.json")
DY = 100

src = json.load(open(PICK, encoding="utf-8"))
配色 = dict(src["配色"])
配色.update({"蓝钮": "#3e8fe0"})

块 = []

def pos_of(b):
    for k in ("块", "凹", "方", "线"):
        if k in b:
            return b[k][:2]
    return (b.get("在") or b.get("圆"))[:2]

# 照搬选关屏（已是 1280 坐标）：左上字标、左栏类型表、右栏背包；去掉返回按钮、顶栏和地图
for b in src["块"]:
    x, y = pos_of(b)
    if (x < 470 and y < 1000) or (x >= 1500 and y >= 250):
        if b.get("占位") == "优惠券：折扣卡":
            b = dict(b, 占位="金色票券")
        块.append(b)

def A(b):
    b = dict(b)
    for k in ("块", "凹", "方", "线"):
        if k in b:
            x0, y0, x1, y1 = b[k]; b[k] = [x0, y0 + DY, x1, y1 + DY]
    if "圆" in b:
        cx, cy, r = b["圆"]; b["圆"] = [cx, cy + DY, r]
    if "在" in b:
        x, y = b["在"]; b["在"] = [x, y + DY]
    块.append(b)

def T(s, x, y, 号, 色="正文", 粗=False, 对齐=None):
    b = {"字": s, "在": [x, y], "号": 号, "色": 色, "粗": 粗}
    if 对齐:
        b["对齐"] = 对齐
    A(b)

# 顶栏
A({"块": [440, 24, 580, 120], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3})
T("$18", 510, 72, 40, "金", True)
A({"块": [600, 24, 1320, 120], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3})
T("商店", 632, 72, 32, "正文", True, "左")
T("第 2/6 段 · 标准难度", 1296, 72, 22, "次字", False, "右")
A({"块": [1500, 24, 1880, 120], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3})
T("方块库", 1524, 72, 22, "次字", False, "左")
T("28", 1790, 72, 48, "正文", True, "右")
T("块", 1802, 72, 22, "次字", False, "左")

# 基因槽与道具栏
A({"块": [500, 150, 1460, 290], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3, "标": "P0 基因与道具"})
T("基因 2/4", 520, 178, 18, "次字", False, "左")
for i in range(4):
    x = 520 + i * 112
    A({"块": [x, 196, x + 100, 276], "色": "内格", "圆角": 10})
    if i < 2:
        A({"占位": "基因图标", "在": [x + 50, 236], "号": 12})
T("拖到这里卖出", 975, 236, 16, "次字", False, "左")
A({"线": [1180, 166, 1180, 274], "色": "面板边", "宽": 2})
T("道具 1/2", 1200, 178, 18, "次字", False, "左")
for i in range(2):
    x = 1200 + i * 112
    A({"块": [x, 196, x + 100, 276], "色": "内格", "圆角": 10})
    if i == 0:
        A({"占位": "改造图标", "在": [x + 50, 236], "号": 12})

# 货架 4 格
A({"块": [500, 310, 1460, 760], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3, "标": "P1 货架"})
T("货架", 520, 338, 18, "次字", False, "左")
GOODS = [
    ("$4", "直脊基因", "普通 · 基因", ["每被消 1 格 I 块", "+1 倍率"], "基因图标"),
    ("$5", "七彩基因", "普通 · 基因", ["被消格有 4 种以上形状", "+10 倍率"], "基因图标"),
    ("$3", "三棱科技", "科技", ["三线 底注 +25", "倍率 +2"], "科技图标"),
    ("$3", "铁芯改造", "改造", ["一块变成铁芯方块"], "改造图标"),
]
for i, (price, name, kind, lines, ph) in enumerate(GOODS):
    x0, y0 = 520 + i * 232, 360
    sel = i == 1
    A({"块": [x0, y0, x0 + 220, y0 + 384], "色": "内格", "圆角": 12, "边": "高亮边" if sel else "面板边", "边宽": 3 if sel else 2})
    A({"块": [x0 + 70, y0 - 14, x0 + 150, y0 + 22], "色": "面板", "圆角": 8, "边": "面板边", "边宽": 2})
    T(price, x0 + 110, y0 + 4, 24, "金", True)
    A({"块": [x0 + 40, y0 + 40, x0 + 180, y0 + 180], "色": "面板", "圆角": 10})
    A({"占位": ph, "在": [x0 + 110, y0 + 110], "号": 13})
    T(name, x0 + 110, y0 + 210, 24, "正文", True)
    T(kind, x0 + 110, y0 + 242, 16, "次字")
    for j, s in enumerate(lines):
        T(s, x0 + 110, y0 + 276 + j * 24, 16, "正文")
    if sel:
        A({"块": [x0 + 30, y0 + 322, x0 + 190, y0 + 368], "色": "蓝钮", "圆角": 8})
        T("购买", x0 + 110, y0 + 345, 22, "正文", True)

# 优惠券 + 补给包
def side(x0, title, price, name, desc, ph):
    A({"块": [x0, 780, x0 + 470, 940], "色": "面板", "圆角": 12, "边": "面板边", "边宽": 3})
    T(title, x0 + 20, 806, 18, "次字", False, "左")
    A({"块": [x0 + 20, 826, x0 + 120, 926], "色": "内格", "圆角": 10})
    A({"占位": ph, "在": [x0 + 70, 876], "号": 12})
    T(name, x0 + 140, 856, 24, "正文", True, "左")
    T(desc, x0 + 140, 896, 18, "次字", False, "左")
    T(price, x0 + 450, 856, 28, "金", True, "右")

side(500, "优惠券 · 本段一张", "$10", "柜台券", "商店货格 +1", "金色票券")
side(990, "补给包", "$4", "基因补给包", "打开后 3 选 1", "绿色箱子")

# 底部按钮
A({"块": [640, 960, 940, 1044], "色": "面板", "圆角": 12, "边": "高亮边", "边宽": 3, "标": "B 刷新"})
T("刷新 $5", 790, 1002, 32, "正文", True)
A({"块": [980, 960, 1280, 1044], "色": "蓝钮", "圆角": 12, "标": "B 离开"})
T("离开商店", 1130, 1002, 32, "正文", True)
A({"块": [1300, 984, 1370, 1020], "色": "内格", "圆角": 6, "边": "面板边", "边宽": 2})
T("Esc", 1335, 1002, 18, "次字")

out = {"名": "3B商店", "说明": __doc__.strip().splitlines()[0], "基准": [1920, 1280], "画布": [1536, 1024], "缩放": 0.8,
       "配色": 配色, "底": 配色["底"], "块": 块}
json.dump(out, open(os.path.join(HERE, "布局_商店.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("ok", len(块))
