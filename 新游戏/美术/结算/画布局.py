DIST = [("单线", 7), ("双线", 3), ("平行线", 1), ("十字", 2), ("拐角", 1), ("三线", 0),
        ("同形态", 1), ("多线", 0), ("同形态十字", 0), ("五线", 0), ("清屏", 0)]
for i, (name, n) in enumerate(DIST):
    c, r = i % 4, i // 4
    x, y = 530 + c * 228, 446 + r * 52
    A({"块": [x, y, x + 214, y + 42], "色": "内格", "圆角": 8})
    A({"字": name, "在": [x + 14, y + 21], "号": 20, "色": "正文" if n else "暗字", "粗": bool(n), "对齐": "左"})
