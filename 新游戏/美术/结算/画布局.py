"""生成结算屏的线框布局 布局_结算.json: python -X utf8 画布局.py

规则 §8.6 草图 + 局外循环 §3.2：左栏消除类型表、右栏科技 / 补给包 / 方块库 / 优惠券都照选关屏，
中间是结算面板（本场、奖励、利息、合计），底部唯一出口「进入商店」。画的是「第 2 段重盲注胜利」那一态。
坐标先按 1920×1080 写，最后整体下移 100 放进 1920×1280（和战斗界面同一画法）。
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PICK = os.path.join(HERE, "..", "选关", "布局_选关.json")
DY = 100

src = json.load(open(PICK, encoding="utf-8"))
配色 = dict(src["配色"])
配色.update({"商店钮": "#3e8fe0"})

块 = []

def pos_of(b):
    for k in ("块", "凹", "方", "线"):
        if k in b:
            return b[k][:2]
    return b.get("在") or b.get("圆")

# 照搬选关屏（已是 1280 坐标）：左上字标、左栏类型表、右栏背包；去掉返回按钮、顶栏和地图
for b in src["块"]:
    x, y = pos_of(b)[:2]
    left = x < 470 and 250 <= y < 1000
    logo = x < 470 and y < 250
    right = x >= 1500 and y >= 250
    if logo or left or right:
        if b.get("占位") == "优惠券：折扣卡":  # 选关屏 B 把这句占位写进了图
            b = dict(b, 占位="金色票券")
        块.append(b)

def A(b):
    b = dict(b)
    for k in ("块", "凹", "方", "线"):
        if k in b:
            x0, y0, x1, y1 = b[k]; b[k] = [x0, y0 + DY, x1, y1 + DY]
    if "圆" in b:
        cx, cy, r = b["圆"]; b["圆"] = [cx, cy + DY, r]
    if "在" in b:
        x, y = b["在"]; b["在"] = [x, y + DY]
    块.append(b)

