for i, b in enumerate(bat["块"]):
    if i in (0, 1) or (12 <= i <= 60 and i != 48):
        块.append(b)
for b in bat["块"]:
    k = next(x for x in ("块", "凹", "方", "线", "圆", "字", "占位", "组") if x in b)
    pos = b.get(k) if k in ("块", "凹", "方", "线") else b.get("在") or b.get("圆")
    if pos and pos[0] < 400 and pos[1] > 1000:
        块.append(b)

def A(b): add(sh(b))

