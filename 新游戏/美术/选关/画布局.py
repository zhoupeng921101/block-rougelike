    """绿色对勾(字体里没有 ✓ 的字形, 用两笔线画)。"""
    A({"线": [x - 8, y, x - 2, y + 7], "色": "勾", "宽": 4})
    A({"线": [x - 2, y + 7, x + 10, y - 8], "色": "勾", "宽": 4})

