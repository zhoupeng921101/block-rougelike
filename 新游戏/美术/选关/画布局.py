块 = []
def add(b):
    块.append(b)

def sh(b):
    """把 1080 坐标的块下移 DY。"""
    b = dict(b)
    for k in ("块", "凹", "方", "线"):
        if k in b:
            x0, y0, x1, y1 = b[k]; b[k] = [x0, y0 + DY, x1, y1 + DY]
    if "圆" in b:
        cx, cy, r = b["圆"]; b["圆"] = [cx, cy + DY, r]
    if "在" in b:
        x, y = b["在"]; b["在"] = [x, y + DY]
    return b

