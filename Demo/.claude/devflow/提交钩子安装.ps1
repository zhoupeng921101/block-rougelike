# 提交钩子安装.ps1 - 把 git 提交前钩子装进客户端仓,让会话外的手动提交也过 UI 绑定核对。
# 钩子落在 .git 下、不随仓入库:新克隆或换机器后跑一次本脚本;hooks\提交前绑定核对.ps1 挪了位置也要重跑。
# 用法:
#   提交钩子安装.ps1 [-RepoDir <仓内任一路径>]              装上;已是本脚本装的旧版则更新
#   提交钩子安装.ps1 [-RepoDir <仓内任一路径>] -CheckOnly   只报现状,零写入
#   提交钩子安装.ps1 [-RepoDir <仓内任一路径>] -Remove      卸掉(只卸本脚本装的)
#   -RepoDir 缺省 = 当前目录所在的仓。
# 写哪里:<git 钩子目录>\pre-commit。钩子目录取 `git rev-parse --git-path hooks`(认 core.hooksPath),
#   主工作树、各槽位与其余 worktree 共用同一份——装一次全仓生效;哪些提交真去核对由钩子体自己判
#   (槽位与合并收尾不拦,见 hooks\提交前绑定核对.ps1 头注)。
# 写什么:一个 sh 垫片,里面是 hooks\提交前绑定核对.ps1 与 hooks\校验库.ps1 的绝对路径。它做两件事:
#   1. 快路径:本次提交没有一个路径落在 UI 绑定核对的读取面里就直接放行,不起 PowerShell(起一次约 2 秒,
#      而绝大多数提交不碰 UI)。读取面的正则每次从 校验库.ps1 的登记行现取,垫片里不存副本。
#   2. 其余情形(命中读取面、正则取不到、git 或 grep 自己出错)一律交给钩子体,由它重新判一遍。
#   快路径只会多放行「钩子体本来也会放行」的提交,拦不拦永远由钩子体定。
# 不覆盖别人的钩子:该位置已有不带本脚本标记行的 pre-commit 时拒绝、原样保留;要并存须人工把两段合进一个文件。
# 前置:无(不需要 Unity,不联网)。调用后:无须别的动作,下一次 git commit 即生效。
# 退出码:0 = INSTALLED / UPDATED / UP-TO-DATE / REMOVED / NOT-INSTALLED / CHECK-*;1 = DENIED-foreign-hook;2 = 参数或 git 错。
# 末行恒为 `VERDICT: <词> | 说明`。
[CmdletBinding(PositionalBinding=$false)]
param(
  [string]$RepoDir = "",
  [switch]$CheckOnly,
  [switch]$Remove
)
$ErrorActionPreference = "Stop"
. (Join-Path $PSScriptRoot "hooks\hook函数库.ps1")

function Write-Verdict([string]$Line, [int]$Code) {
  Write-Host ("VERDICT: " + $Line)
  exit $Code
}

try {
  $base = if ($RepoDir) { $RepoDir } else { (Get-Location).Path }
  if (-not (Test-Path -LiteralPath $base)) { Write-Verdict ("DENIED-repo | 路径不存在:" + $base) 2 }
  $root = Get-GitOne $base "rev-parse --show-toplevel"
  if (-not $root) { Write-Verdict ("DENIED-repo | 无法解析 git 仓根(-RepoDir / 当前目录 = " + $base + ")") 2 }

  $hooksDir = Get-GitOne $root "rev-parse --git-path hooks"
  if (-not $hooksDir) { Write-Verdict "INFRA | git rev-parse --git-path hooks 无输出" 2 }
  if (-not [System.IO.Path]::IsPathRooted($hooksDir)) { $hooksDir = Join-Path $root $hooksDir }
  $hooksDir = [System.IO.Path]::GetFullPath($hooksDir)
  $hookFile = Join-Path $hooksDir "pre-commit"

  $hookBody = Join-Path $PSScriptRoot "hooks\提交前绑定核对.ps1"
  if (-not (Test-Path -LiteralPath $hookBody)) { Write-Verdict ("INFRA | 钩子体不存在:" + $hookBody) 2 }

  $checkLib = Join-Path $PSScriptRoot "hooks\校验库.ps1"
  if (-not (Test-Path -LiteralPath $checkLib)) { Write-Verdict ("INFRA | 读取面登记所在的脚本不存在:" + $checkLib) 2 }

  # 垫片:LF 行尾、UTF-8 无 BOM(sh 不认 BOM,首行 #! 前多三个字节即整份失效)。引擎写裸名,与 settings.json 的 hook 入口同口径。
  # 快路径的三个退出码各有去向,别合并:grep 回 1 = 确实没有一条命中 -> 放行;回 0 = 命中;回 2 = grep 自己出错
  # (如正则用了它不认的写法)。后两种都往下交给钩子体。git diff 失败时 if 不成立,同样往下。
  # 用 grep -P:登记的是 .NET 正则,PCRE 与它最接近;换成 -E,遇到 \d 这类写法不报错而是按别的意思匹配,会静默放错。
  # 取路径带 core.quotepath=false:缺省下中文文件名被加引号转义,行首多出一个引号,带 ^ 的正则恒不命中。
  $marker = "# flow-hook: pre-commit-uibind"
  $template = @'
#!/bin/sh
__MARKER__ (generated by 提交钩子安装.ps1; re-run it to update or remove, do not edit)
re=$(grep -F '"UI绑定核对.ps1"' "__LIB__" 2>/dev/null | sed -n "s/^[^=]*= *'\(.*\)'.*$/\1/p" | head -n 1)
if [ -n "$re" ] && staged=$(git -c core.quotepath=false diff --cached --name-only --no-renames 2>/dev/null); then
  printf '%s\n' "$staged" | grep -q -P -- "$re"
  [ $? -eq 1 ] && exit 0
fi
exec powershell.exe -NoProfile -ExecutionPolicy Bypass -File "__BODY__"
'@
  $want = $template.Replace("`r`n", "`n").Replace("__MARKER__", $marker).Replace("__LIB__", $checkLib.Replace('\', '/')).Replace("__BODY__", $hookBody.Replace('\', '/')) + "`n"

  $have = $null
  if (Test-Path -LiteralPath $hookFile) { $have = [System.IO.File]::ReadAllText($hookFile, [System.Text.Encoding]::UTF8) }
  $state = if ($null -eq $have) { "absent" }
           elseif ($have -ceq $want) { "current" }
           elseif ($have.IndexOf($marker, [System.StringComparison]::Ordinal) -ge 0) { "outdated" }
           else { "foreign" }

  if ($CheckOnly) {
    switch ($state) {
      "absent"   { Write-Verdict ("CHECK-NOT-INSTALLED | " + $hookFile + " 不存在;不带 -CheckOnly 重跑即装上") 0 }
      "current"  { Write-Verdict ("CHECK-INSTALLED | " + $hookFile + " 已是当前版本") 0 }
      "outdated" { Write-Verdict ("CHECK-OUTDATED | " + $hookFile + " 是本脚本装的旧版(钩子体路径或垫片内容已变);不带 -CheckOnly 重跑即更新") 0 }
      default    { Write-Verdict ("CHECK-FOREIGN | " + $hookFile + " 是别处写的钩子,本脚本不会覆盖它") 0 }
    }
  }

  if ($state -eq "foreign") {
    Write-Verdict ("DENIED-foreign-hook | " + $hookFile + " 已有别处写的钩子,原样保留;要并存须人工把垫片那一行并进去") 1
  }

  if ($Remove) {
    if ($state -eq "absent") { Write-Verdict ("NOT-INSTALLED | " + $hookFile + " 本就不存在") 0 }
    [System.IO.File]::Delete($hookFile)
    Write-Verdict ("REMOVED | 已卸掉 " + $hookFile) 0
  }

  if ($state -eq "current") { Write-Verdict ("UP-TO-DATE | " + $hookFile + " 已是当前版本,未写入") 0 }
  [void][System.IO.Directory]::CreateDirectory($hooksDir)
  [System.IO.File]::WriteAllText($hookFile, $want, (New-Object System.Text.UTF8Encoding($false)))
  $word = if ($state -eq "outdated") { "UPDATED" } else { "INSTALLED" }
  Write-Verdict ($word + " | " + $hookFile + " -> " + $hookBody) 0
} catch {
  Write-Verdict ("INFRA | 内部异常:" + [string]$_) 2
}
